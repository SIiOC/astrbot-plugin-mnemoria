def build_transcript(turns: list[tuple[str, str]], max_chars: int = 4000,
                     user_label: str = "用户") -> str:
    """把 (role, content) 列表拼成对话文本，超长时保留最近的部分。

    v0.1.6：用户侧带身份锚点（angel 同款）——transcript 里模型抄得到
    的真名才会出现在记忆里；裸「用户」输入只能产出「用户…」记忆。
    """
    lines = []
    for role, content in turns:
        who = f"[{user_label}]" if role == "user" else "[助理]"
        lines.append(f"{who}: {content}")
    text = "\n".join(lines)
    if len(text) > max_chars:
        text = "…（前略）\n" + text[-max_chars:]
    return text
